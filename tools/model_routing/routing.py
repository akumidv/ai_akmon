# Context-pressure detection (design §12, ADR 0006) — the tokens axis of runtime weakness
# --------------------------------------------------------------------------------------


def context_fill(usage: dict | None) -> int | None:
    """Context-window fill at a turn: the three input components partition the prompt.

    ``output_tokens`` is not context carried forward, so it is excluded. ``None`` when the
    usage carries no input component at all — the caller stays silent rather than warn
    from a guess.
    """
    if not isinstance(usage, dict):
        return None
    components = [
        usage.get(key)
        for key in ("input_tokens", "cache_read_input_tokens", "cache_creation_input_tokens")
    ]
    if not any(isinstance(value, int) for value in components):
        return None
    return sum(value for value in components if isinstance(value, int))


def context_window(registry: dict, model_id: str | None) -> int:
    """The model's context window: an alias-substring exception from ``windows``, else the default."""
    policy = registry.get("context_pressure", {})
    default = int(policy.get("window_default") or 200000)
    windows = policy.get("windows", {})
    if model_id and isinstance(windows, dict):
        lowered = model_id.lower()
        matches = [key for key in windows if key and key.lower() in lowered]
        if matches:
            return int(windows[max(matches, key=len)])
    return default


def _context_fill_metrics(
    registry: dict, transcript_path: str | Path | None
) -> tuple[int, int, float] | None:
    """``(fill, window, ratio)`` for the last main-chain turn; ``None`` if unavailable.

    Shared by ``context_pressure_notice`` (banded warnings) and ``context_fill_ratio``
    (the C29 axis-2 coefficient) so both read the same fill/window definition.
    """
    model_id, usage = _last_main_turn(transcript_path)
    fill = context_fill(usage)
    if fill is None:
        return None
    window = context_window(registry, model_id)
    if window <= 0:
        return None
    return fill, window, fill / window


def context_fill_ratio(registry: dict, transcript_path: str | Path | None) -> float | None:
    """Context-window fill ratio (0..~1+) for the last main-chain turn; ``None`` if unavailable.

    Reused by the C29 output-weight nudge to weight cumulative tool-output bytes by how
    full the window already is — the same signal ``context_pressure_notice`` bands.
    """
    metrics = _context_fill_metrics(registry, transcript_path)
    return metrics[2] if metrics else None


def context_pressure_notice(
    registry: dict,
    transcript_path: str | Path | None,
    session_id: str | None,
    *,
    marker_dir: Path | None = None,
) -> list[str]:
    """Warning lines when the context fill crossed a *new* warn band; ``[]`` otherwise.

    Banded and throttled (the delegation-nudge marker idiom): a per-session temp-dir
    marker records the last announced band, so only a band *rise* warns — 0→high once,
    high→critical once more, a steady fill stays silent. A fill dropping below the lowest
    band (a compaction landed) clears the marker, so each compaction cycle gets its own
    warnings. Missing/malformed usage → silent; never raises past I/O.
    """
    policy = registry.get("context_pressure", {})
    ratios = [float(r) for r in policy.get("warn_ratios") or [] if isinstance(r, (int, float))]
    if not ratios:
        return []
    metrics = _context_fill_metrics(registry, transcript_path)
    if metrics is None:
        return []
    fill, window, ratio = metrics
    band: int | None = None
    for index, threshold in enumerate(ratios):
        if ratio >= threshold:
            band = index

    marker = (marker_dir or Path(tempfile.gettempdir())) / f"akmon-context-pressure-{session_id or 'nosession'}"
    try:
        last_band: int | None = int(marker.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        last_band = None

    if band is None:
        # Below every band — a compaction (or a fresh session) resets the throttle.
        try:
            marker.unlink(missing_ok=True)
        except OSError:
            pass
        return []
    if last_band is not None and band <= last_band:
        return []
    try:
        marker.write_text(str(band), encoding="utf-8")
    except OSError:
        pass

    critical = band == len(ratios) - 1 and len(ratios) > 1
    advice = (
        "critical — compact now (/compact) or finish the current unit of work first"
        if critical
        else "checkpoint durable state (files/TASKS) and plan compaction"
    )
    return [f"⚠ context pressure: ~{ratio:.0%} of {window // 1000}k ({fill} tokens) — {advice}"]


def binding_artifacts(
    registry: dict, binding: Binding, *, second_opinion: bool, available: list[str] | None
) -> dict[str, str]:
    """Every generated routing artifact as ``project-root-relative path → content``.

    The generated ``k-*`` subagent definitions plus the local config — the single set the
    init tool and the SessionStart/UserPromptSubmit hook both write, so a rebind from
    either path produces byte-identical files.
    """
    files = dict(generated_agent_files(registry, binding))
    config = local_config(binding, registry, second_opinion=second_opinion, available=available)
    files[LOCAL_CONFIG_REL] = json.dumps(config, indent=2) + "\n"
    return files


def write_artifacts(root: Path, files: dict[str, str], *, write: bool = True) -> list[Path]:
    """Write each artifact whose content changed; return the changed paths (idempotent)."""
    changed: list[Path] = []
    for rel, content in files.items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        changed.append(path)
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return changed


def rebind_to(
    root: Path, registry: dict, config: dict, orchestrator: str, *, write: bool = True
) -> tuple[Binding, list[Path]]:
    """Recompute the binding for ``orchestrator`` and (re)write the artifacts under ``root``.

    Reuses the recorded ``available`` list and opt-ins from ``config`` — only the
    orchestrator moves. Idempotent: unchanged files are left untouched. This is how the
    hook makes subagent models follow the session's actual orchestrating model.
    """
    available = config.get("available")
    second_opinion = bool(config.get("second_opinion"))
    vendor = str(config.get("vendor") or "anthropic")
    binding = compute_binding(registry, orchestrator, available, vendor)
    files = binding_artifacts(registry, binding, second_opinion=second_opinion, available=available)
    return binding, write_artifacts(root, files, write=write)


def local_config(binding: Binding, registry: dict, *, second_opinion: bool, available: list[str] | None) -> dict:
    config = {
        "vendor": binding.vendor,
        "orchestrator": binding.orchestrator,
        "binding": {
            "reasoner": binding.reasoner,
            "worker": binding.worker,
            "mid": binding.mid,
            "auditor": binding.auditor,
            "escalation": list(binding.escalation),
        },
        "second_opinion": second_opinion,
        "second_opinion_provider": opposite_vendor(registry, binding.vendor),
        "available": available,
        "registry_hash": registry_hash(registry),
        "task_kind_floors": task_kind_floors(registry, available or []),
    }
    provider = config["second_opinion_provider"]
    if provider == binding.vendor:
        rungs = list(available) if available else _semantic_rungs(registry.get(binding.vendor, {}))
        config["second_opinion_fallback_model"] = second_opinion_fallback_model(
            rungs, binding.orchestrator, binding.auditor
        )
    return config


def staleness(config: dict, registry: dict, settings_model: str | None) -> str | None:
    """Why the local config is stale — or None when it is fresh."""
    if not config:
        return "no local config — model routing is not initialized"
    if config.get("registry_hash") != registry_hash(registry):
        return "registry (or project overlay) changed since init"
    if settings_model and settings_model != config.get("orchestrator"):
        return f"settings default model '{settings_model}' differs from configured orchestrator"
    return None


