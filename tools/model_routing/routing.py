def _agent_model(spec: AgentSpec, binding: Binding) -> str | None:
    if binding.semantic_fallback:
        return None
    return {
        "worker": binding.worker,
        "mid": binding.mid,
        "reasoner": binding.reasoner,
        "auditor": binding.auditor,
    }[spec.tier]


def agent_file_content(spec: AgentSpec, binding: Binding, brief_extra: str = "") -> str:
    lines = ["---", f"name: {spec.name}", "description: >-"]
    lines.extend(f"  {chunk}" for chunk in _wrap(spec.description, 88))
    if spec.tools:
        lines.append(f"tools: {spec.tools}")
    model = _agent_model(spec, binding)
    if model:
        lines.append(f"model: {model}")
    lines.append("---")
    lines.append("")
    lines.append(f"<!-- {GENERATED_BANNER} -->")
    lines.append("")
    lines.append(spec.body)
    if brief_extra.strip():
        lines.append("")
        lines.append("<!-- project overlay brief -->")
        lines.append("")
        lines.append(brief_extra.strip())
    return "\n".join(lines) + "\n"


def _wrap(text: str, width: int) -> list[str]:
    words = text.split()
    chunks: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) > width and current:
            chunks.append(current)
            current = word
        else:
            current = candidate
    if current:
        chunks.append(current)
    return chunks


def generated_agent_files(registry: dict, binding: Binding) -> dict[str, str]:
    """Map of ``.claude/agents/<name>.md`` relative paths → generated content."""
    briefs = registry.get("briefs", {})
    return {
        f"{AGENTS_DIR_REL}/{spec.name}.md": agent_file_content(spec, binding, briefs.get(spec.name, ""))
        for spec in AGENT_SPECS
    }


_AGENT_BY_NAME: dict[str, AgentSpec] = {spec.name: spec for spec in AGENT_SPECS}


def subagent_kinds(name: str) -> tuple[str, ...]:
    """Task kinds a generated subagent covers; empty for a host built-in / unknown name."""
    spec = _AGENT_BY_NAME.get(name)
    return spec.kinds if spec else ()


def bound_model_for(config: dict, subagent_type: str) -> str | None:
    """Model a generated ``k-*`` agent is pinned to — its tier's binding alias, or None.

    The generated agent frontmatter carries ``model: <alias>`` (see ``_agent_model``), but an
    ``Agent`` call rarely echoes it — so the delegation record shows ``-`` and the console
    line omits the model. Deriving it from the recorded binding restores it. None for an
    unknown agent (a host built-in) or a semantic-fallback binding whose tier value is not a
    real alias (mirrors ``_agent_model`` emitting no ``model:`` line in that mode).
    """
    spec = _AGENT_BY_NAME.get(subagent_type)
    if spec is None or not isinstance(config, dict):
        return None
    binding = config.get("binding")
    if not isinstance(binding, dict):
        return None
    model = binding.get(spec.tier)
    if not model:
        return None
    available = config.get("available") or []
    if available and model not in available:
        return None
    return str(model)


_ROLE_DECL_RE = re.compile(r"🧭\s*agent:\s*([A-Za-z][\w-]*)")


def _assistant_text(entry: dict) -> str:
    message = entry.get("message")
    if not isinstance(message, dict):
        return ""
    content = message.get("content")
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return " ".join(
            block.get("text", "")
            for block in content
            if isinstance(block, dict) and block.get("type") == "text"
        )
    return ""


def active_role(transcript_path: str | Path | None) -> str | None:
    """The role the orchestrator last declared (``🧭 agent: <name>``), read from the transcript.

    The chat declaration is invisible to a hook as chat, but the transcript records it in the
    assistant turns a hook can already scan (as C22/C23 do). Only main-chain assistant turns
    are read, so the SessionStart reminder / a subagent echo never masquerades as the
    declaration. Returns the last-declared name (the caller maps it to a role row), else None.
    """
    if not transcript_path:
        return None
    path = Path(transcript_path)
    if not path.is_file():
        return None
    role: str | None = None
    try:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                # Cheap ascii pre-filter: the emoji may be \u-escaped in the JSONL, but
                # "agent:" is always literal. json.loads then decodes the real marker.
                if "agent:" not in line:
                    continue
                try:
                    entry = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if not isinstance(entry, dict) or entry.get("type") != "assistant" or entry.get("isSidechain"):
                    continue
                for match in _ROLE_DECL_RE.finditer(_assistant_text(entry)):
                    role = match.group(1)
    except OSError:
        return None
    return role


def role_matrix_warning(registry: dict, subagent_type: str, role: str | None) -> str | None:
    """Advisory (§10.2): the routed agent has no task kind the active role may route.

    Subagent granularity — the call carries the agent, not the specific kind — so warn only
    when *none* of the agent's kinds intersect the role's allowed row. That catches an edit
    agent routed under the analysis-only ``review`` role without false-flagging a multi-kind
    agent (e.g. ``k-reasoner``) that shares one legitimate kind. None when the role is
    unknown/undeclared or the agent is a host built-in (no kinds).

    **Cross-cutting verification kinds** (``cross_cutting_kinds`` — ``independent-review`` and
    ``audit``) are *not* role-gated (A7 (b), §10.2): any role may route them and *when* they
    apply is the structural trigger (§9.5), not the producing role. They join every role's
    allowed set, so an agent whose only kinds are cross-cutting (e.g. ``k-auditor``) never
    warns under any role.
    """
    if not role:
        return None
    allowed = registry.get("role_task_kinds", {}).get(role)
    if not allowed:
        return None
    allowed = set(allowed) | set(registry.get("cross_cutting_kinds", []))
    kinds = subagent_kinds(subagent_type)
    if not kinds or set(kinds) & allowed:
        return None
    return (
        f"role/task-kind: {subagent_type} ({', '.join(kinds)}) is outside the active role "
        f"'{role}' — it routes {', '.join(allowed)}. Re-route or switch role."
    )


