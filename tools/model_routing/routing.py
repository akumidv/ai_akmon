def local_config(binding: Binding, registry: dict, *, second_opinion: bool, available: list[str] | None) -> dict:
    config = {
        "vendor": binding.vendor,
        "orchestrator": binding.orchestrator,
        "binding": {
            "reasoner": binding.reasoner,
            "worker": binding.worker,
            "mid": binding.mid,
            "synthesizer": binding.synthesizer,
            "escalation": list(binding.escalation),
        },
        "second_opinion": second_opinion,
        "second_opinion_provider": opposite_vendor(registry, binding.vendor),
        "available": available,
        "registry_hash": registry_hash(registry),
        "task_kind_floors": task_kind_floors(registry, available or []),
    }
    provider = config["second_opinion_provider"]
    if provider == binding.vendor:
        rungs = list(available) if available else _semantic_rungs(registry.get(binding.vendor, {}))
        config["second_opinion_fallback_model"] = second_opinion_fallback_model(
            rungs, binding.orchestrator, binding.synthesizer
        )
    return config


def staleness(config: dict, registry: dict, settings_model: str | None) -> str | None:
    """Why the local config is stale — or None when it is fresh."""
    if not config:
        return "no local config — model routing is not initialized"
    if config.get("registry_hash") != registry_hash(registry):
        return "registry (or project overlay) changed since init"
    if settings_model and settings_model != config.get("orchestrator"):
        return f"settings default model '{settings_model}' differs from configured orchestrator"
    return None


def status_lines(config: dict, registry: dict, forge: str) -> list[str]:
    """The steady-state status injection: one binding line + self-check, plus any warning."""
    binding = config.get("binding", {})
    second = "on" if config.get("second_opinion") else "off"
    orchestrator_vendor = str(config.get("vendor") or "anthropic")
    provider = second_opinion_provider(registry, config, orchestrator_vendor)
    second_cli = registry.get(provider, {}).get("second_opinion", {}).get("cli", "-")
    orchestrator = config.get("orchestrator", "?")
    lines = [
        "[keystone] model routing: "
        f"vendor={orchestrator_vendor} · orchestrator={orchestrator} · reasoner={binding.get('reasoner', '?')} · "
        f"synthesizer={binding.get('synthesizer', '?')} · "
        f"worker={binding.get('worker', '?')} · mid={binding.get('mid', '?')} · "
        f"second-opinion={second_cli}({second})",
        "Delegation is the default — route by task kind (MODEL.md § Capability tiers): "
        "k-explorer/k-mechanic/k-validator (worker) · k-implementer (mid) · k-reasoner · "
        "k-synthesizer (synthesis-verify at gates); escalate one rung only on failure signals.",
        f"Self-check: if your actual model is not '{orchestrator}', re-run "
        f"`python3 {forge}/keystone/tools/model_routing/init.py --orchestrator <alias>`.",
    ]
    warning = compute_binding(registry, orchestrator, config.get("available"), orchestrator_vendor).warning
    if warning:
        lines.append(f"⚠ {warning}")
    return lines


def init_instruction(reason: str, forge: str) -> list[str]:
    return [
        f"[keystone] Model routing needs initialization — {reason}.",
        "State the model you are running on and the models available in this harness, then run: "
        f"`python3 {forge}/keystone/tools/model_routing/init.py --orchestrator <your-alias> "
        "[--available <alias,...>] [--second-opinion on|off]`.",
        "Then ask the owner to (a) confirm the proposed tier→model binding and "
        "(b) enable or decline second-opinion review, and re-run the tool with their answers.",
    ]


