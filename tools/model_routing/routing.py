_SUBAGENT_TOOLS = frozenset({"Task", "Agent"})


def delegation_log_line(tool_name: str, tool_input: dict, timestamp: str) -> str | None:
    """One TSV line per subagent delegation; None for any other tool."""
    if tool_name not in _SUBAGENT_TOOLS:
        return None
    subagent = str(tool_input.get("subagent_type") or "-")
    model = str(tool_input.get("model") or "-")
    description = " ".join(str(tool_input.get("description") or "").split())
    return f"{timestamp}\t{subagent}\t{model}\t{description}"
