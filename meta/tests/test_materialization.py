"""common/materialization.json — the shared banner fragments and imported directories (C102)."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from common import jsondata, materialization
from common.project_root import aitna_root_name

_ROOT = Path("/somewhere/proj")  # no ``.aitna-root`` there: the default dev root


def test_materialization_json_carries_the_banner_and_dirs():
    data = json.loads((Path(materialization.__file__).parent / "materialization.json").read_text(encoding="utf-8"))
    assert set(data) == {"generated_banner", "imported_dirs"}
    assert data["generated_banner"]["prefix"] == "Generated by "
    assert data["generated_banner"]["suffix"] == "/akmon/bin/sync.py. Do not edit this file by hand."
    assert data["imported_dirs"] == ["guardrails", "profiles"]


def test_the_banner_tracks_the_configured_root(tmp_path):
    assert materialization.generated_banner(tmp_path) == (
        f"Generated by {aitna_root_name(tmp_path)}/akmon/bin/sync.py. Do not edit this file by hand."
    )
    assert "Generated by _aitna/akmon/" in materialization.generated_banner(tmp_path)
    (tmp_path / ".aitna-root").write_text("tools/ai\n", encoding="utf-8")
    assert materialization.generated_banner(tmp_path).startswith("Generated by tools/ai/akmon/bin/sync.py.")
    assert materialization.generated_marker() == "Generated by "
    assert materialization.imported_dirs() == ("guardrails", "profiles")


def test_the_loader_reads_exactly_materialization_json(monkeypatch):
    seen: list[Path] = []
    real_read = jsondata.read

    def capture(path):
        seen.append(path)
        return real_read(path)

    monkeypatch.setattr(jsondata, "read", capture)
    materialization.generated_marker()
    materialization.generated_banner(_ROOT)
    materialization.imported_dirs()
    assert seen == [Path(materialization.__file__).with_name("materialization.json")] * 3


def test_a_missing_data_file_fails_from_the_public_functions(monkeypatch):
    def broken(path):
        raise jsondata.DataFileError(f"akmon data file missing: {path}")

    monkeypatch.setattr(jsondata, "read", broken)
    with pytest.raises(jsondata.DataFileError):
        materialization.generated_marker()
    with pytest.raises(jsondata.DataFileError):
        materialization.generated_banner(_ROOT)
